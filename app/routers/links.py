
from datetime import timezone
from typing import Annotated

from fastapi import (
    APIRouter,
    Depends,
    HTTPException,
    Request,
    status,
)
from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from app.auth.dependencies import get_current_client
from app.core.db import get_db
from app.models import ApiClient, Link
from app.schemas.link import LinkCreate, LinkResponse
from app.utils.base62 import generate_short_code


router = APIRouter(
    prefix="/api/links",
    tags=["Links"],
)


@router.post(
    "",
    response_model=LinkResponse,
    status_code=status.HTTP_201_CREATED,
)
def create_link(
    payload: LinkCreate,
    request: Request,
    client: Annotated[ApiClient, Depends(get_current_client)],
    db: Annotated[Session, Depends(get_db)],
):
    """Create a persistent short link for an authenticated client."""

    # Convert timezone-aware expiration to UTC for MySQL DATETIME.
    expires_at = None

    if payload.expires_at is not None:
        expires_at = payload.expires_at.astimezone(
            timezone.utc
        ).replace(tzinfo=None)

    # Reject an alias that is already used.
    if payload.custom_alias:
        existing = db.scalar(
            select(Link).where(
                Link.code == payload.custom_alias
            )
        )

        if existing is not None:
            raise HTTPException(
                status_code=status.HTTP_409_CONFLICT,
                detail="Custom alias already exists",
            )

    # Create the record using the authenticated client's ID.
    link = Link(
        long_url=str(payload.long_url),
        client_id=client.id,
        expires_at=expires_at,
        code=payload.custom_alias,
    )

    try:
        db.add(link)

        # INSERT the row to obtain its generated database ID.
        db.flush()

        # Generate scrambled Base62 only for automatic codes.
        if payload.custom_alias is None:
            try:
                link.code = generate_short_code(link.id)
            except ValueError:
                db.rollback()
                raise HTTPException(
                    status_code=status.HTTP_503_SERVICE_UNAVAILABLE,
                    detail="Short-code capacity exhausted",
                )

        # Write the generated code to the database.
        db.flush()

        # Commit both changes as one transaction.
        db.commit()

    except IntegrityError:
        db.rollback()
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail="Short code or alias already exists",
        )

    # Load values generated by SQLAlchemy or MySQL.
    db.refresh(link)

    short_url = (
        str(request.base_url).rstrip("/") + "/" + link.code
    )

    return LinkResponse(
        id=link.id,
        code=link.code,
        long_url=link.long_url,
        short_url=short_url,
        expires_at=link.expires_at,
        created_at=link.created_at,
    )
